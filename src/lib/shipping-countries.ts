const regionNames = new Intl.DisplayNames(["en"], { type: "region" });

/** "ET" → "Ethiopia"; falls back to the code if the runtime doesn't know it. */
export function countryName(code: string) {
  try {
    return regionNames.of(code) ?? code;
  } catch {
    return code;
  }
}
